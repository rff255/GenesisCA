import { useEffect, useLayoutEffect, useMemo, useRef, useState } from 'react';
import type { CAModel } from '../model/types';
import { createdDateTimestamp, formatCreatedDate } from '../model/createdDate';
import { ThumbMedia } from '../components/ThumbMedia';
import styles from './ModelsLibrary.module.css';

interface LibraryEntry {
  id: string;
  name: string;
  author: string;
  modelAuthor?: string;
  description: string;
  file: string;
  tags: string[];
  gridSize: string;
  /** '2d' | '3d' — emitted by the Vite plugin (3d iff the model uses the depth
   *  axis). Absent on an index.json generated by an older build → treat as 2d. */
  dimension?: '2d' | '3d';
  /** Topology layers (from CAModel.topologyMode; a model can have BOTH).
   *  Absent on an older index.json → grid on, agents off (the schema default). */
  hasGrid?: boolean;
  hasAgents?: boolean;
  /** The model's AUTHORED creation date (`YYYY-MM-DD`, from
   *  `properties.createdDate`) — powers the Newest/Oldest sort + the card date
   *  stamp. Absent when the author never set one: the card then shows NO date
   *  and the entry sorts last under Newest/Oldest, because the alternative
   *  (the file's mtime, which every build churns) was actively misleading. */
  createdDate?: string;
  /** Sidecar filename (e.g. `"Game Of Life.gcaproj.thumb.gif"`, or `.thumb.webm`
   *  for a video thumbnail) emitted by the Vite plugin. Absent when the source
   *  .gcaproj has no embedded thumbnail. */
  thumbnail?: string;
}

interface Props {
  onLoadModel: (model: CAModel, fileName?: string) => void;
}

// ---------------------------------------------------------------------------
// Browse preferences (search / category / dimension / sort / grouping) —
// persisted so the library reopens the way the user left it.
// ---------------------------------------------------------------------------
type SortKey = 'name-asc' | 'name-desc' | 'newest' | 'oldest' | 'grid-desc';
type DimFilter = 'all' | '2d' | '3d';
interface LibraryPrefs {
  q: string;
  tag: string;
  dim: DimFilter;
  /** Topology quick filters — independent TOGGLES, not a radio (a model can
   *  have a CA grid AND agents at once): each one, when on, requires that
   *  layer; both on = models running both; both off = no topology filtering. */
  grid: boolean;
  agents: boolean;
  sort: SortKey;
  group: boolean;
}

const PREFS_KEY = 'genesisca_library_prefs';
const DEFAULT_PREFS: LibraryPrefs = { q: '', tag: '', dim: 'all', grid: false, agents: false, sort: 'name-asc', group: false };
const SORT_OPTIONS: ReadonlyArray<{ key: SortKey; label: string }> = [
  { key: 'name-asc', label: 'Name A→Z' },
  { key: 'name-desc', label: 'Name Z→A' },
  { key: 'newest', label: 'Newest' },
  { key: 'oldest', label: 'Oldest' },
  { key: 'grid-desc', label: 'Largest grid' },
];

function loadPrefs(): LibraryPrefs {
  try {
    const raw = localStorage.getItem(PREFS_KEY);
    if (!raw) return DEFAULT_PREFS;
    const p = JSON.parse(raw) as Partial<LibraryPrefs>;
    return {
      q: typeof p.q === 'string' ? p.q : '',
      tag: typeof p.tag === 'string' ? p.tag : '',
      dim: p.dim === '2d' || p.dim === '3d' ? p.dim : 'all',
      grid: !!p.grid,
      agents: !!p.agents,
      sort: SORT_OPTIONS.some(o => o.key === p.sort) ? (p.sort as SortKey) : 'name-asc',
      group: !!p.group,
    };
  } catch {
    return DEFAULT_PREFS;
  }
}

/** Total cell count parsed from the "WxH" / "WxHxD" grid-size string. */
function cellCount(e: LibraryEntry): number {
  return e.gridSize.split('x').reduce((acc, part) => acc * (Number(part) || 1), 1);
}

const byName = (a: LibraryEntry, b: LibraryEntry) =>
  a.name.localeCompare(b.name, undefined, { sensitivity: 'base' });

/** Sortable timestamp for a card's authored creation date (null when unset). */
function createdTs(e: LibraryEntry): number | null {
  return createdDateTimestamp(e.createdDate);
}

/**
 * Newest/Oldest comparator. Entries with NO authored date sort LAST in BOTH
 * directions (then by name) — an undated model has no place on a time axis, and
 * pretending it does is exactly the misleading behaviour the mtime stamp had.
 */
function byCreated(a: LibraryEntry, b: LibraryEntry, newestFirst: boolean): number {
  const ta = createdTs(a), tb = createdTs(b);
  if (ta === null && tb === null) return byName(a, b);
  if (ta === null) return 1;
  if (tb === null) return -1;
  return (newestFirst ? tb - ta : ta - tb) || byName(a, b);
}

// ---------------------------------------------------------------------------
// Effective tags — the tag set the card / filter / group / category-dropdown
// machinery sees: the model's authored tags PLUS synthetic "mode" tags (3D,
// Agents) derived from its dimension + topology, so those two badges filter,
// group, and list in the category dropdown exactly like a real tag. The
// synthetic ones come FIRST (so grouping keys a 3D / Agents model under that
// mode) and REPLACE any redundant hand-authored tag of the same name (the
// de-dup — a 3D model that also carries a literal "3D" tag shows it once, as
// the badge). Only the NON-default modes get a synthetic tag — 2D and CA-Grid
// are the norm on nearly every model, so badging them would be noise.
type TagKind = 'dim3d' | 'agents' | null;
interface EffTag { key: string; label: string; kind: TagKind; }

// Authored-tag spellings a present synthetic tag subsumes (dropped from the
// grey chips, shown once as the badge instead).
const SYNTH_ALIASES: Record<'dim3d' | 'agents', string[]> = {
  dim3d: ['3d'],
  agents: ['agents', 'agent'],
};

function effectiveTags(e: LibraryEntry): EffTag[] {
  const synth: EffTag[] = [];
  const drop = new Set<string>();
  if ((e.dimension ?? '2d') === '3d') {
    synth.push({ key: '3d', label: '3D', kind: 'dim3d' });
    SYNTH_ALIASES.dim3d.forEach(a => drop.add(a));
  }
  if (e.hasAgents) {
    synth.push({ key: 'agents', label: 'Agents', kind: 'agents' });
    SYNTH_ALIASES.agents.forEach(a => drop.add(a));
  }
  const seen = new Set(drop);          // seeded with the stripped synthetic dups
  const authored: EffTag[] = [];
  for (const t of e.tags) {
    const label = t.trim();
    const key = label.toLowerCase();
    if (!key || seen.has(key)) continue;  // strip synthetic dups + repeated tags
    seen.add(key);
    authored.push({ key, label, kind: null });
  }
  return [...synth, ...authored];
}

// ---------------------------------------------------------------------------
// Hover preview popover: a two-pane panel — [title + description | thumbnail]
// side by side, SAME size — centered horizontally on the card and placed just
// ABOVE it (flips below when there's no room). Models without a thumbnail get
// the description pane alone.
// ---------------------------------------------------------------------------
const POPOVER_GAP = 8;

interface CardRect {
  top: number;
  bottom: number;
  left: number;
  right: number;
}

interface HoverState {
  name: string;
  description: string;
  thumbnail?: string;
  cardRect: CardRect;
}

function computePopoverPosition(
  card: CardRect,
  popoverWidth: number,
  popoverHeight: number,
): { top: number; left: number } {
  const viewportW = window.innerWidth;
  const viewportH = window.innerHeight;
  // Centered ON the hovered card — both axes — so the panel literally sits on
  // top of it (`pointer-events: none` lets hover + clicks pass through to the
  // card beneath). Clamped to the viewport for cards near an edge, so the
  // centring is "to the best of the available space".
  let left = (card.left + card.right) / 2 - popoverWidth / 2;
  left = Math.max(POPOVER_GAP, Math.min(viewportW - popoverWidth - POPOVER_GAP, left));
  let top = (card.top + card.bottom) / 2 - popoverHeight / 2;
  top = Math.max(POPOVER_GAP, Math.min(viewportH - popoverHeight - POPOVER_GAP, top));
  return { top, left };
}

// ---------------------------------------------------------------------------
// The auto-scroll rule, shared by the card description AND the popover's
// description pane: when the text overflows its clipped viewport and the
// reader rests on it, it slowly scrolls to the end, holds, scrolls back, and
// loops. Driven by rAF with direct style writes (no React re-render per
// frame); text that fits does nothing.
// ---------------------------------------------------------------------------
function useAutoScrollOverflow(
  outerRef: React.RefObject<HTMLDivElement | null>,
  innerRef: React.RefObject<HTMLDivElement | null>,
  active: boolean,
  text: string,
): void {
  useEffect(() => {
    const outer = outerRef.current, inner = innerRef.current;
    if (!outer || !inner) return;
    if (!active) {
      inner.style.transition = 'transform 0.25s ease';
      inner.style.transform = 'translateY(0)';
      return;
    }
    const dist = inner.scrollHeight - outer.clientHeight;
    if (dist <= 4) return;  // fits (or nearly) — nothing to reveal
    // Phase timeline per cycle: rest at top → scroll down (~25 px/s) → hold at
    // the end → scroll back up → repeat (the top rest doubles as the loop hold).
    const DELAY = 800, HOLD_END = 1400, UP = 450;
    const downMs = Math.max(1200, dist * 40);
    const cycle = DELAY + downMs + HOLD_END + UP;
    const start = performance.now();
    inner.style.transition = 'none';
    let raf = 0;
    const tick = (now: number) => {
      let t = (now - start) % cycle;
      let y: number;
      if (t < DELAY) y = 0;
      else if ((t -= DELAY) < downMs) y = (t / downMs) * dist;
      else if ((t -= downMs) < HOLD_END) y = dist;
      else y = dist * (1 - (t - HOLD_END) / UP);
      inner.style.transform = `translateY(${-y}px)`;
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [outerRef, innerRef, active, text]);
}

/** Clipped, hover-auto-scrolling description inside a card. */
function ScrollingDesc({ text, hovered }: { text: string; hovered: boolean }) {
  const outerRef = useRef<HTMLDivElement>(null);
  const innerRef = useRef<HTMLDivElement>(null);
  useAutoScrollOverflow(outerRef, innerRef, hovered, text);
  return (
    <div ref={outerRef} className={styles.cardDesc}>
      <div ref={innerRef} className={styles.cardDescInner}>{text}</div>
      <div className={styles.cardDescFade} />
    </div>
  );
}

/** The popover's left pane: title + full description, auto-scrolling (always
 *  "hovered" — the popover only exists while the card is) when too long for
 *  the pane. */
function PopoverDescPane({ title, text }: { title: string; text: string }) {
  const outerRef = useRef<HTMLDivElement>(null);
  const innerRef = useRef<HTMLDivElement>(null);
  useAutoScrollOverflow(outerRef, innerRef, true, text);
  return (
    <div className={styles.previewDescPane}>
      <div className={styles.previewTitle}>{title}</div>
      <div ref={outerRef} className={styles.previewDescScroll}>
        <div ref={innerRef} className={styles.cardDescInner}>{text}</div>
        <div className={styles.previewDescFade} />
      </div>
    </div>
  );
}

export function ModelsLibrary({ onLoadModel }: Props) {
  const [entries, setEntries] = useState<LibraryEntry[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [prefs, setPrefs] = useState<LibraryPrefs>(loadPrefs);
  const [hoveredId, setHoveredId] = useState<string | null>(null);
  const [hover, setHover] = useState<HoverState | null>(null);
  const [popoverPos, setPopoverPos] = useState<{ top: number; left: number } | null>(null);
  const popoverRef = useRef<HTMLDivElement>(null);

  // The popover is rendered first (invisible), measured, then positioned — the
  // only way to place a content-sized box exactly without guessing its size
  // (one pane or two). useLayoutEffect runs before paint, so the unpositioned
  // frame is never shown.
  useLayoutEffect(() => {
    if (!hover || !popoverRef.current) return;
    setPopoverPos(computePopoverPosition(hover.cardRect, popoverRef.current.offsetWidth, popoverRef.current.offsetHeight));
  }, [hover]);

  useEffect(() => {
    const base = import.meta.env.BASE_URL ?? '/';
    fetch(`${base}models/index.json`)
      .then(r => {
        if (!r.ok) throw new Error(`Failed to load library index (${r.status})`);
        return r.json();
      })
      .then((data: LibraryEntry[]) => {
        setEntries(data);
        setLoading(false);
      })
      .catch(err => {
        setError(err instanceof Error ? err.message : 'Failed to load library.');
        setLoading(false);
      });
  }, []);

  // Persist browse preferences (small object — write directly on change).
  useEffect(() => {
    try { localStorage.setItem(PREFS_KEY, JSON.stringify(prefs)); } catch { /* full */ }
  }, [prefs]);

  // Effective tags per entry (authored + the synthetic 3D / Agents mode tags),
  // computed once — every downstream consumer (catalogue, filter, group, card)
  // reads from here so the synthetic tags behave uniformly.
  const effTagsById = useMemo(() => {
    const m = new Map<string, EffTag[]>();
    for (const e of entries) m.set(e.id, effectiveTags(e));
    return m;
  }, [entries]);

  // Category catalogue: case-insensitive canonical tags (incl. the synthetic
  // 3D / Agents) with usage counts, sorted by frequency then name.
  const tagCatalog = useMemo(() => {
    const map = new Map<string, { label: string; count: number }>();
    for (const e of entries) {
      for (const t of effTagsById.get(e.id) ?? []) {
        const cur = map.get(t.key);
        if (cur) cur.count++;
        else map.set(t.key, { label: t.label, count: 1 });
      }
    }
    return [...map.entries()]
      .map(([key, v]) => ({ key, ...v }))
      .sort((a, b) => b.count - a.count || a.label.localeCompare(b.label, undefined, { sensitivity: 'base' }));
  }, [entries, effTagsById]);

  // Filter + sort pipeline.
  const visible = useMemo(() => {
    const q = prefs.q.trim().toLowerCase();
    const out = entries.filter(e => {
      const eff = effTagsById.get(e.id) ?? [];
      if (prefs.dim !== 'all' && (e.dimension ?? '2d') !== prefs.dim) return false;
      // Topology toggles: each one, when on, REQUIRES that layer (independent
      // toggles — both on means "runs the grid AND agents together").
      if (prefs.grid && !(e.hasGrid ?? true)) return false;
      if (prefs.agents && !(e.hasAgents ?? false)) return false;
      // Category filter matches EFFECTIVE tags, so selecting "3D" / "Agents"
      // (badge or dropdown) filters like any authored tag.
      if (prefs.tag && !eff.some(t => t.key === prefs.tag)) return false;
      if (q) {
        const hay = `${e.name} ${e.description} ${e.author} ${e.modelAuthor ?? ''} ${eff.map(t => t.label).join(' ')}`.toLowerCase();
        if (!hay.includes(q)) return false;
      }
      return true;
    });
    switch (prefs.sort) {
      case 'name-desc': out.sort((a, b) => byName(b, a)); break;
      case 'newest': out.sort((a, b) => byCreated(a, b, true)); break;
      case 'oldest': out.sort((a, b) => byCreated(a, b, false)); break;
      case 'grid-desc': out.sort((a, b) => cellCount(b) - cellCount(a) || byName(a, b)); break;
      default: out.sort(byName);
    }
    return out;
  }, [entries, prefs, effTagsById]);

  // Group-by-category view: sections keyed by each model's FIRST tag (its
  // primary category); untagged models fall into "Other". Groups sort by size.
  const groups = useMemo(() => {
    if (!prefs.group) return null;
    const map = new Map<string, { label: string; items: LibraryEntry[] }>();
    for (const e of visible) {
      const first = (effTagsById.get(e.id) ?? [])[0];
      const key = first ? first.key : '__other';
      const g = map.get(key);
      if (g) g.items.push(e);
      else map.set(key, { label: first ? first.label : 'Other', items: [e] });
    }
    return [...map.values()].sort((a, b) =>
      b.items.length - a.items.length || a.label.localeCompare(b.label, undefined, { sensitivity: 'base' }));
  }, [visible, prefs.group, effTagsById]);

  const handleClick = async (entry: LibraryEntry) => {
    try {
      const base = import.meta.env.BASE_URL ?? '/';
      const r = await fetch(`${base}models/${entry.file}`);
      if (!r.ok) throw new Error(`Failed to load model (${r.status})`);
      const model = (await r.json()) as CAModel;
      onLoadModel(model, entry.file);
    } catch (err) {
      alert(err instanceof Error ? err.message : 'Failed to load model.');
    }
  };

  const handleCardEnter = (entry: LibraryEntry, el: HTMLElement) => {
    setHoveredId(entry.id);
    if (!entry.thumbnail && !entry.description.trim()) { setHover(null); return; }
    const base = import.meta.env.BASE_URL ?? '/';
    const r = el.getBoundingClientRect();
    setPopoverPos(null); // hidden until useLayoutEffect measures + positions it
    setHover({
      name: entry.name,
      description: entry.description,
      thumbnail: entry.thumbnail ? `${base}models/${entry.thumbnail}` : undefined,
      cardRect: { top: r.top, bottom: r.bottom, left: r.left, right: r.right },
    });
  };

  const handleCardLeave = () => {
    setHoveredId(null);
    setHover(null);
  };

  /** Toggle the category filter from a card's tag chip. */
  const toggleTagFilter = (tag: string) => {
    const key = tag.trim().toLowerCase();
    setPrefs(p => ({ ...p, tag: p.tag === key ? '' : key }));
  };

  const renderCard = (entry: LibraryEntry) => (
    <div
      key={entry.id}
      className={styles.card}
      onClick={() => handleClick(entry)}
      onMouseEnter={e => handleCardEnter(entry, e.currentTarget)}
      onMouseLeave={handleCardLeave}
    >
      <div className={styles.cardName} title={entry.name}>{entry.name}</div>
      {entry.author && (
        <div className={styles.cardAuthor} title={`Rule by: ${entry.author}`}>Rule by: {entry.author}</div>
      )}
      {entry.modelAuthor && (
        <div className={styles.cardAuthor} title={`Project by: ${entry.modelAuthor}`}>Project by: {entry.modelAuthor}</div>
      )}
      <ScrollingDesc text={entry.description} hovered={hoveredId === entry.id} />
      {/* The meta block WRAPS so every tag stays visible — tags take layout
          priority over the description (which is clipped anyway and shown in
          full by the hover preview); the description viewport above absorbs
          whatever height the wrapped tag rows leave. The synthetic 3D / Agents
          mode tags render as coloured BADGES; authored tags as grey chips. All
          are clickable and toggle the SAME category filter, and highlight when
          they're the active one — so a badge behaves exactly like a tag. */}
      <div className={styles.cardMeta}>
        {(effTagsById.get(entry.id) ?? []).map(t => {
          const active = prefs.tag === t.key;
          const cls = t.kind === 'dim3d'
            ? `${styles.dimBadge} ${active ? styles.dimBadgeActive : ''}`
            : t.kind === 'agents'
              ? `${styles.agentBadge} ${active ? styles.agentBadgeActive : ''}`
              : `${styles.tag} ${active ? styles.tagActive : ''}`;
          return (
            <span
              key={t.key}
              className={cls}
              title={`Filter by "${t.label}"`}
              onClick={e => { e.stopPropagation(); toggleTagFilter(t.key); }}
            >{t.label}</span>
          );
        })}
        <span
          className={styles.gridSize}
          title={entry.createdDate ? `Created ${formatCreatedDate(entry.createdDate, true)}` : undefined}
        >
          {entry.gridSize.replace(/x/g, '×')}
          {entry.createdDate ? ` · ${formatCreatedDate(entry.createdDate, false)}` : ''}
        </span>
      </div>
    </div>
  );

  const filtersActive = !!(prefs.q.trim() || prefs.tag || prefs.dim !== 'all' || prefs.grid || prefs.agents);

  return (
    <div className={styles.layout}>
      <h1 className={styles.title}>Models Library</h1>
      <p className={styles.subtitle}>
        Explore pre-made cellular automata models. Click one to load it in the Modeler.
      </p>

      {loading && <p className={styles.loading}>Loading library...</p>}
      {error && <p className={styles.error}>{error}</p>}

      {!loading && !error && (
        <div className={styles.toolbar}>
          <input
            type="text"
            className={styles.searchInput}
            placeholder="Search models…"
            value={prefs.q}
            onChange={e => setPrefs(p => ({ ...p, q: e.target.value }))}
          />
          <select
            className={styles.toolbarSelect}
            value={prefs.tag}
            onChange={e => setPrefs(p => ({ ...p, tag: e.target.value }))}
            title="Filter by category (tag)"
          >
            <option value="">All categories</option>
            {tagCatalog.map(t => (
              <option key={t.key} value={t.key}>{t.label} ({t.count})</option>
            ))}
          </select>
          <div className={styles.dimSeg} title="Filter by grid dimension">
            {(['all', '2d', '3d'] as const).map(d => (
              <button
                key={d}
                className={`${styles.dimSegBtn} ${prefs.dim === d ? styles.dimSegBtnActive : ''}`}
                onClick={() => setPrefs(p => ({ ...p, dim: d }))}
              >{d === 'all' ? 'All' : d.toUpperCase()}</button>
            ))}
          </div>
          {/* Topology quick filters — independent TOGGLES (a model can run the
              CA grid and agents simultaneously, so these aren't a radio). */}
          <div className={styles.dimSeg} title="Filter by topology — toggles: each one requires that layer; both on = models running both">
            <button
              className={`${styles.dimSegBtn} ${prefs.grid ? styles.dimSegBtnActive : ''}`}
              aria-pressed={prefs.grid}
              title="Only models with a CA-grid (lattice) layer"
              onClick={() => setPrefs(p => ({ ...p, grid: !p.grid }))}
            >CA Grid</button>
            <button
              className={`${styles.dimSegBtn} ${prefs.agents ? styles.dimSegBtnActive : ''}`}
              aria-pressed={prefs.agents}
              title="Only models with a Bond-Graph Agents layer"
              onClick={() => setPrefs(p => ({ ...p, agents: !p.agents }))}
            >Agents</button>
          </div>
          <select
            className={styles.toolbarSelect}
            value={prefs.sort}
            onChange={e => setPrefs(p => ({ ...p, sort: e.target.value as SortKey }))}
            title="Sort order"
          >
            {SORT_OPTIONS.map(o => (
              <option key={o.key} value={o.key}>Sort: {o.label}</option>
            ))}
          </select>
          <label className={styles.groupToggle} title="Group the cards into sections by their primary tag">
            <input
              type="checkbox"
              checked={prefs.group}
              onChange={e => setPrefs(p => ({ ...p, group: e.target.checked }))}
            />
            Group by category
          </label>
          <span className={styles.resultCount}>
            {filtersActive ? `${visible.length} of ${entries.length}` : `${entries.length}`} models
            {filtersActive && (
              <button
                className={styles.clearFilters}
                onClick={() => setPrefs(p => ({ ...p, q: '', tag: '', dim: 'all', grid: false, agents: false }))}
                title="Clear search + filters"
              >Clear</button>
            )}
          </span>
        </div>
      )}

      {!loading && !error && visible.length === 0 && (
        <p className={styles.loading}>No models match the current filters.</p>
      )}

      {groups ? (
        groups.map(g => (
          <div key={g.label}>
            <div className={styles.groupHeader}>
              {g.label} <span className={styles.groupCount}>{g.items.length}</span>
            </div>
            <div className={styles.grid}>{g.items.map(renderCard)}</div>
          </div>
        ))
      ) : (
        <div className={styles.grid}>{visible.map(renderCard)}</div>
      )}

      {hover && (
        <div
          ref={popoverRef}
          className={styles.previewPopover}
          style={
            popoverPos
              ? { top: popoverPos.top, left: popoverPos.left }
              : { visibility: 'hidden' }
          }
        >
          <PopoverDescPane title={hover.name} text={hover.description} />
          {hover.thumbnail && (
            <ThumbMedia src={hover.thumbnail} className={styles.previewThumb} />
          )}
        </div>
      )}
    </div>
  );
}
